def test_generation_prompt_caps_whole_project_context():
    project_files = {
        f"src/file-{index}.py": "x" * 4000
        for index in range(30)
    }
    prompt = build_generation_prompt(
        task_desc="Investigate the reported project issue",
        category="Software Development",
        constraints="",
        output_style="Balanced",
        include_checklist=True,
        project_files=project_files
    )

    imported_context = prompt.split("=== IMPORTED PROJECT REFERENCE FILES ===\n", 1)[1]
    included_content = [
        section.split("---\n", 1)[1].split("\n", 1)[0]
        for section in imported_context.split("--- File: ")[1:]
    ]
    assert sum(len(content) for content in included_content) <= MAX_PROJECT_CONTEXT_CHARS
    assert "additional file(s) were not included" in imported_context
    assert "Do not claim an unverified cause or fix" in prompt

class SimpleMonkeyPatch:
    def setattr(self, target, value):
        mod_name, attr = target.rsplit(".", 1)
        import importlib
        mod = importlib.import_module(mod_name)
        setattr(mod, attr, value)

