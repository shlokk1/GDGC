def test_zip_exporter():
    content = "---\nname: test-skill\ndescription: Test description\n---\n# Test\n"
    project_files = {
        "config.yaml": "version: 1\nsetting: enabled\n",
        "script.py": "print('hello from imported project')\n"
    }
    zip_bytes = create_skill_zip("test-skill", content, project_files=project_files)
    assert len(zip_bytes) > 0

    # Read back zip in memory
    zf = zipfile.ZipFile(io.BytesIO(zip_bytes))
    file_list = zf.namelist()
    assert "test-skill/SKILL.md" in file_list
    assert "test-skill/MANIFEST.txt" in file_list
    assert "test-skill/references/config.yaml" in file_list
    assert "test-skill/references/script.py" in file_list
    
    extracted_skill = zf.read("test-skill/SKILL.md").decode("utf-8")
    assert extracted_skill == content
    extracted_yaml = zf.read("test-skill/references/config.yaml").decode("utf-8")
    assert "setting: enabled" in extracted_yaml

