def test_generate_skill_with_ollama_retries_invalid_frontmatter(monkeypatch=None):
    if monkeypatch is None:
        monkeypatch = SimpleMonkeyPatch()
    valid_content = """---
name: retried-skill
description: A valid skill returned after a format retry.
---
# Purpose
Describe the skill purpose.
## Workflow
1. Inspect the request.
## Rules & Constraints
- Follow the task constraints.
"""

    class FakeOllamaClient:
        def __init__(self, endpoint, default_model):
            self.calls = 0

        def generate(self, prompt, system, model, temperature=0.2):
            self.calls += 1
            if self.calls == 1:
                return {"success": True, "response": "---\nname: invalid\nnot valid yaml\n---\n"}
            assert "Previous response" in prompt
            return {"success": True, "response": valid_content, "model": model}

    monkeypatch.setattr("generator.skill_generator.OllamaClient", FakeOllamaClient)
    result = generate_skill_with_ollama("Write a local skill")
    assert result["name"] == "retried-skill"

def test_ollama_read_timeout_does_not_retry_generation(monkeypatch):
    calls = []

    def timeout_post(url, json, timeout):
        calls.append(url)
        raise requests.exceptions.ReadTimeout("inference is still running")

    monkeypatch.setattr("generator.ollama_client.requests.post", timeout_post)
    result = OllamaClient().generate("Generate a skill")

    assert result["success"] is False
    assert str(int(GENERATION_TIMEOUT_SECONDS)) in result["error"]
    assert calls == ["http://localhost:11434/api/chat"]

def test_ollama_uses_generate_endpoint_only_when_chat_is_unsupported(monkeypatch):
    class Response:
        def __init__(self, status_code, payload):
            self.status_code = status_code
            self.text = ""
            self.payload = payload

        def json(self):
            return self.payload

    responses = [
        Response(404, {}),
        Response(200, {"response": "generated skill"})
    ]
    calls = []

    def post(url, json, timeout):
        calls.append(url)
        return responses.pop(0)

    monkeypatch.setattr("generator.ollama_client.requests.post", post)
    result = OllamaClient().generate("Generate a skill")

    assert result["success"] is True
    assert result["response"] == "generated skill"
    assert calls == [
        "http://localhost:11434/api/chat",
        "http://localhost:11434/api/generate"
    ]

